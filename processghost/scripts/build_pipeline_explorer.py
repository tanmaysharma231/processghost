"""Render the decision register (markdown) and the interactive pipeline explorer (HTML) from
scripts/pipeline_spec.py.

    python -m scripts.build_pipeline_explorer                  # writes docs/25-decision-register.md and docs/pipeline-explorer.html
    python -m scripts.build_pipeline_explorer --fragment F     # also writes the HTML without its document wrapper (for publishing)

Prompts and settings are read from the code at build time, so the page shows what the code actually does.
tests/test_pipeline_explorer.py fails if the committed files are stale.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any, Dict, List

from scripts import pipeline_spec as spec

DOCS = spec.DOCS
OPT_IN = {  # stage id -> the command-line option that enables it
    "screen": "--screen", "surface": "--screen", "align": "--screen", "reconcile": "--screen", "investigate": "--screen",
    "document": "--workbook",
}
KIND_LABEL = {"llm": "LLM", "code": "CODE", "hybrid": "LLM + CODE"}
STATUS_NOTE = {
    "built": "built and exercised",
    "partial": "built, with known problems or unproven on real data",
    "planned": "designed, not built",
}


# --------------------------------------------------------------------------------------------------
# Shared data
# --------------------------------------------------------------------------------------------------
def build_data() -> Dict[str, Any]:
    stages = []
    for s in spec.all_stages():
        stages.append(
            {
                **{k: s[k] for k in ("id", "num", "name", "lane", "kind", "status", "short", "inputs", "outputs", "model", "tree", "failure", "measured", "issues")},
                "optin": OPT_IN.get(s["id"], ""),
                "knobs": [{"name": n, "value": spec.knob_value(n)} for n in s["knobs"]],
                "prompts": [{"name": n, "text": spec.prompt_text(n)} for n in s["prompts"]],
            }
        )
    return {"stages": stages, "decisions": spec.all_decisions(), "questions": spec.OPEN_QUESTIONS}


# --------------------------------------------------------------------------------------------------
# Markdown register
# --------------------------------------------------------------------------------------------------
def _tone_word(tone: str) -> str:
    return {"warn": " (degrades)", "stop": " (stops)"}.get(tone, "")


def _flat(text: str) -> str:
    return " ".join(text.split())


def render_markdown() -> str:
    data = build_data()
    stages = {s["id"]: s for s in data["stages"]}
    lines: List[str] = [
        "# 25 - Decision register",
        "",
        "Generated by `python -m scripts.build_pipeline_explorer` from `scripts/pipeline_spec.py`; do not edit by hand.",
        "The interactive version, with every prompt in a collapsible box, is `pipeline-explorer.html`.",
        "",
        "Everything the pipeline decides, in one place: what each stage does as a decision tree, what happens when",
        "it fails, which settings control it (current values), every design decision with what was rejected, and",
        "the questions still open.",
        "",
        "## Status legend",
        "",
        "| Status | Meaning |",
        "|---|---|",
    ]
    lines += [f"| {k} | {v} |" for k, v in STATUS_NOTE.items()]
    lines += ["", "Kinds: **LLM** calls a model; **CODE** is plain Python; **LLM + CODE** calls a model and verifies or acts on its answer in code.", "", "## The pipeline at a glance", "", "| Stage | Kind | Status | Runs | What happens on failure |", "|---|---|---|---|---|"]
    for s in data["stages"]:
        runs = f"with `{s['optin']}`" if s["optin"] else "always"
        lines.append(f"| {s['num']} {s['name']} | {KIND_LABEL[s['kind']]} | {s['status']} | {runs} | {_flat(s['failure'])} |")

    lines += ["", "## Stage by stage", ""]
    for s in data["stages"]:
        lines += [f"### {s['num']} - {s['name']}", "", f"{s['short']}", "", f"- Kind: {KIND_LABEL[s['kind']]} | Status: {s['status']} | Model: {s['model']}" + (f" | Runs only with `{s['optin']}`" if s["optin"] else "")]
        lines.append("- Takes in: " + "; ".join(s["inputs"]))
        lines.append("- Produces: " + "; ".join(s["outputs"]))
        if s["prompts"]:
            lines.append("- Prompt: " + ", ".join(f"`{p['name']}` (full text in `docs/21-pipeline-reference.md` and the explorer)" for p in s["prompts"]))
        lines += ["", "**Decision tree**", ""]
        for i, step in enumerate(s["tree"], 1):
            note = f" _{step['note']}_" if step["note"] else ""
            lines.append(f"{i}. {step['step']}{note}")
            for b in step["branches"]:
                lines.append(f"   - IF {b['if']} -> {b['then']}{_tone_word(b['tone'])}")
        lines += ["", f"**On failure:** {s['failure']}", ""]
        if s["knobs"]:
            lines += ["**Settings** (current values from `core/config.py`)", "", "| Setting | Value |", "|---|---|"]
            lines += [f"| `{k['name']}` | `{k['value']}` |" for k in s["knobs"]]
            lines.append("")
        decs = [d for d in data["decisions"] if s["id"] in d["stages"]]
        if decs:
            lines += ["**Decisions that shaped it:** " + "; ".join(f"{d['id']} {d['title']}" for d in decs), ""]
        if s["measured"]:
            lines += ["**Measured**", ""] + [f"- {m}" for m in s["measured"]] + [""]
        if s["issues"]:
            lines += ["**Known issues**", ""] + [f"- {m}" for m in s["issues"]] + [""]

    lines += ["## All decisions", "", f"{len(data['decisions'])} decisions: D1 to D20 from `22-architecture-v3.md`, ADR 1 to 9 from `adr/`, and X1 to X7 settled in working sessions.", ""]
    for d in data["decisions"]:
        names = ", ".join(stages[x]["name"] for x in d["stages"] if x in stages) or "cross-cutting"
        lines += [f"### {d['id']} - {d['title']}", "", f"- Status: {d['status']}" + (f" ({d['status_note']})" if d.get("status_note") else ""), f"- Applies to: {names}", f"- Why: {_flat(d['why'])}", f"- Rejected: {_flat(d['rejected'])}", f"- Source: {d['source']}", ""]

    lines += ["## Open questions", "", "Decisions not yet made, or problems without a fix.", ""]
    for q in data["questions"]:
        names = ", ".join(stages[x]["name"] for x in q["stages"] if x in stages)
        lines += [f"### {q['id']} - {q['title']}", "", f"- Applies to: {names}", f"- Why it matters: {_flat(q['why'])}", "- Options: " + "; ".join(q["options"]), ""]
    return "\n".join(lines).rstrip() + "\n"


